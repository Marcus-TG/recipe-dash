/**
 * Conventional produce lives in the 3000/4000 series. A leading 9 marks the
 * same food grown organically, and 83000-84999 was set aside for GMO produce
 * that never used it — both resolve to the same food, which is all the pantry
 * cares about.
 */
export function lookupPlu(code: string): string | null {
  const digits = code.replace(/\D/g, '')
  if (PLU_NAMES[digits]) return PLU_NAMES[digits]!
  if (digits.length === 5 && (digits.startsWith('9') || digits.startsWith('8'))) {
    return PLU_NAMES[digits.slice(1)] ?? null
  }
  return null
}

/** Is this plausibly a PLU rather than a store SKU? */
export function looksLikePlu(code: string): boolean {
  return lookupPlu(code) != null
}
